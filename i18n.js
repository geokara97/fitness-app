// Translate a key, filling {placeholders} from vars. Falls back to English, then the key.
function t(key, vars) {
    let s = STRINGS[LANG][key] ?? STRINGS.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
    }
    return s;
}

function setLang(lang) {
    if (!SUPPORTED_LANGS.includes(lang) || lang === LANG) return;
    try { localStorage.setItem(LANG_STORAGE_KEY, lang); } catch (e) { /* ignore */ }
    window.location.reload();
}

// Fill static markup: data-i18n (text), data-i18n-placeholder, data-i18n-title.
function applyI18n(root = document) {
    document.documentElement.lang = LANG;
    root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
}

// Registered before the page scripts' handlers, so it runs first.
document.addEventListener('DOMContentLoaded', () => applyI18n());
